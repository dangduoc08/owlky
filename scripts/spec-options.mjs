const code = (value) => `\`${value}\``;

function html(schema, spec) {
  const where = spec.children ? ` on each ${code(spec.children.replace(":scope > ", ""))}` : "";
  switch (spec.kind) {
    case "style":
      return `${code(`${spec.attr}="…"`)}${where}`;
    case "flag":
    case "native":
      return `${code(spec.attr)}${where}`;
    case "number":
      return code(`${spec.attr}="…"`);
    case "behavior":
      return `${code(`${spec.attr}="false"`)} turns it off`;
    default:
      return `${code(spec.attr)}${spec.event ? ` · event ${code(`ok:${schema.name}:${spec.event}`)}` : ""}`;
  }
}

function values(spec) {
  if (spec.kind === "style") return spec.values.map(code).join(" ");
  if (spec.kind === "number")
    return spec.units ? `number (px) or ${spec.units.map(code).join(" ")} length` : "number";
  return spec.kind === "state" ? "—" : "boolean";
}

function fallback(spec) {
  if (spec.kind === "style") return spec.optional ? "—" : code(spec.default);
  if (spec.kind === "behavior") return spec.default ? "on" : "off";
  if (spec.kind === "state") return "—";
  if (spec.kind === "number") return spec.default === undefined ? "—" : code(spec.default);
  return "off";
}

function table(schema) {
  const rows = Object.entries(schema.options).map(
    ([key, spec]) =>
      `| ${code(key)} | ${html(schema, spec)} | ${spec.kind}${spec.when ? ` (with ${code(spec.when)})` : ""} | ${values(spec)} | ${fallback(spec)} | ${spec.description.replaceAll("|", "\\|")} |`,
  );
  return [
    `Root: ${code(schema.root)}. Unknown values fall back to the default.`,
    "",
    "| React | HTML | Kind | Values | Default | Description |",
    "|---|---|---|---|---|---|",
    ...rows,
  ].join("\n");
}

const check = process.argv.includes("--check");
const stale = [];
for (const [name, file] of Object.entries(SPECS)) {
  const path = new URL(`../specs/components/${file}`, import.meta.url);
  const source = readFileSync(path, "utf8");
  const open = `<!-- options:${name} (generated by \`pnpm specs:options\` from the schema in packages/core/src/anatomy/anatomy.ts) -->`;
  const close = `<!-- /options:${name} -->`;
  const start = source.indexOf(`<!-- options:${name} `);
  const end = source.indexOf(close);
  if (start === -1 || end === -1) {
    stale.push(`${file}: missing the options:${name} markers`);
    continue;
  }
  const next = `${source.slice(0, start)}${open}\n${table(optionSchemas[name])}\n${source.slice(end)}`;
  if (next === source) continue;
  if (check) stale.push(`${file}: options:${name} is out of date`);
  else writeFileSync(path, next);
}
if (stale.length > 0) {
  console.error(`${stale.join("\n")}\nRun \`pnpm build && pnpm specs:options\`.`);
  process.exit(1);
}
console.log(check ? "specs: options tables are up to date" : "specs: options tables written");
