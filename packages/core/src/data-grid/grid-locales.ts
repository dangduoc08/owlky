/** "1–10 of 25" from a `paginationDisplayedRows` pattern. */
export const gridDisplayedRows = (
  pattern: string,
  range: { from: number; to: number; count: number },
): string =>
  pattern
    .replaceAll("{from}", String(range.from))
    .replaceAll("{to}", String(range.to))
    .replaceAll("{count}", String(range.count));
